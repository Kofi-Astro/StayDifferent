/**
 * Small helper to build a length ladder: each step up in length adds `step`
 * to the price. `stock` is a list of stock counts, one per length.
 * @param {number[]} lengths
 * @param {number} from   Price of the shortest length.
 * @param {number} step   Price increase per length step.
 * @param {number[]} stock
 * @returns {import('./types').Variant[]}
 */
function ladder(lengths, from, step, stock) {
  return lengths.map((length, i) => ({ length, price: from + step * i, compareAt: null, stock: stock[i] ?? 0 }));
}

